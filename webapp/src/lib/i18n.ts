export type Lang = 'en' | 'ru';

export function langFrom(code: string | null | undefined): Lang {
  const l = (code ?? '').trim().toLowerCase().slice(0, 2);
  return l === 'ru' || l === 'uk' || l === 'kk' || l === 'be' ? 'ru' : 'en';
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const table: Record<Key, string> = lang === 'ru' ? RU : EN;
  return (key, vars) => {
    const s = table[key] ?? EN[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

/** Has key: for dynamic keys built from server enums (kind_*, nk_*, st_* …). */
export function isKey(k: string): k is Key {
  return k in EN;
}

export const I18nContext = createContext<{ t: T; lang: Lang }>({ t: makeT('en'), lang: 'en' });
export function useT(): { t: T; lang: Lang } {
  return useContext(I18nContext);
}

// ── formatting helpers (the user's own time zone comes from /api/me)
export function fmtTime(ms: number, lang: Lang, tz?: string): string {
  try {
    return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-GB', { weekday: 'short', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', ...(tz ? { timeZone: tz } : {}) }).format(new Date(ms));
  } catch {
    return new Date(ms).toISOString().slice(0, 16).replace('T', ' ');
  }
}
export function fmtDate(ms: number, lang: Lang, tz?: string): string {
  try {
    return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric', ...(tz ? { timeZone: tz } : {}) }).format(new Date(ms));
  } catch {
    return new Date(ms).toISOString().slice(0, 10);
  }
}
export function fmtRelative(ms: number, now: number, lang: Lang): string {
  const diff = ms - now;
  const abs = Math.abs(diff);
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });
  if (abs < 60_000) return rtf.format(Math.round(diff / 1000), 'second');
  if (abs < 3_600_000) return rtf.format(Math.round(diff / 60_000), 'minute');
  if (abs < 86_400_000) return rtf.format(Math.round(diff / 3_600_000), 'hour');
  return rtf.format(Math.round(diff / 86_400_000), 'day');
}

/** t() for keys built from server enums; falls back to the raw value when there is no string. */
export function tDyn(t: T, key: string, fallback: string, vars?: Record<string, string | number>): string {
  return isKey(key) ? t(key, vars) : fallback;
}
